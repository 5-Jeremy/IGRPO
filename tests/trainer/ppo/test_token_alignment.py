"""Original-token alignment for cleanup, alternate BPE splits, and Unicode."""

import numpy as np
import pytest
import torch
from huggingface_hub import snapshot_download
from huggingface_hub.errors import LocalEntryNotFoundError
from tokenizers import Tokenizer, decoders, models, pre_tokenizers
from transformers import AutoTokenizer, PreTrainedTokenizerFast

from agent_system.reasoning_advantage import attach_reasoning_token_ids, adjust_reasoning_advantages
from agent_system.reasoning_entropy import attach_reasoning_entropy
from agent_system.reasoning_steps import attach_reasoning_steps
from agent_system.token_alignment import response_token_offsets
from verl import DataProto


@pytest.fixture
def byte_tokenizer():
    # Full byte vocabulary, with one merge that generation need not choose.
    vocab = {token: index for index, token in enumerate(
        ["[PAD]", *sorted(pre_tokenizers.ByteLevel.alphabet()), ".Ċ"])}
    backend = Tokenizer(models.BPE(vocab=vocab, merges=[(".", "Ċ")]))
    backend.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False, use_regex=False)
    backend.decoder = decoders.ByteLevel()
    return PreTrainedTokenizerFast(tokenizer_object=backend, pad_token="[PAD]",
                                  clean_up_tokenization_spaces=True)


def make_token_batch(tokenizer, ids):
    responses = torch.tensor([[tokenizer.pad_token_id, *ids, tokenizer.pad_token_id]])
    mask = (responses != tokenizer.pad_token_id).long()
    return DataProto.from_dict(tensors={
        "responses": responses, "attention_mask": mask, "response_mask": mask,
        "loss_mask": mask.clone(), "advantages": torch.ones_like(responses, dtype=torch.float32),
        "returns": torch.ones_like(responses, dtype=torch.float32),
    }, non_tensors={"id": np.array(["turn"], dtype=object), "is_action_valid": np.array([True])})


def test_noncanonical_tokens_cleanup_unicode_and_probability_adjustment(byte_tokenizer):
    tokenizer = byte_tokenizer
    output = "<think>Found it .\nCheck café 🙂?\nChoose it.</think><action>look</action>"
    canonical = tokenizer.encode(output, add_special_tokens=False)
    merge_id = tokenizer.convert_tokens_to_ids(".Ċ")
    split_ids = tokenizer.convert_tokens_to_ids([".", "Ċ"])
    ids = [piece for token in canonical for piece in (split_ids if token == merge_id else [token])]
    assert ids != canonical
    assert tokenizer.decode(ids, skip_special_tokens=True) != output  # Default cleanup removes the space.
    assert tokenizer.decode(ids, skip_special_tokens=True, clean_up_tokenization_spaces=False) == output
    batch = make_token_batch(tokenizer, ids)
    attach_reasoning_steps(batch, tokenizer, None)
    assert batch.non_tensor_batch["reasoning_trace"][0]["steps"] == ["Found it .", "Check café 🙂?", "Choose it."]
    attach_reasoning_token_ids(batch, tokenizer, None)
    assert batch.non_tensor_batch["reasoning_alignment_status"].tolist() == ["aligned"]
    for number, text in enumerate(batch.non_tensor_batch["reasoning_trace"][0]["steps"], 1):
        selected = batch.batch["reasoning_step_ids"][0] == number
        assert tokenizer.decode(batch.batch["responses"][0, selected], clean_up_tokenization_spaces=False) == text
    assert batch.batch["reasoning_step_ids"][0, [0, -1]].tolist() == [0, 0]

    # Initial support earns a bonus; repeated support keeps the baseline.
    support = "The reasoning step supports the chosen action"
    batch.non_tensor_batch["decision_model_probabilities"] = np.array([{
        "step_1": {support: 1.0}, "step_2": {support: 1.0},
        "step_3": {"The reasoning step contradicts the chosen action": 1.0},
    }], dtype=object)
    first = batch.batch["reasoning_step_ids"] == 1
    masked_position = first[0].nonzero()[0].item()
    batch.batch["loss_mask"][0, masked_position] = 0
    metrics = adjust_reasoning_advantages(batch)
    expected = torch.ones_like(batch.batch["advantages"])
    expected[first & batch.batch["loss_mask"].bool()] = 1.3
    expected[batch.batch["reasoning_step_ids"] == 3] = -1
    torch.testing.assert_close(batch.batch["advantages"], expected)
    assert torch.all(batch.batch["returns"] == 1)
    assert metrics["reasoning_advantage/scored_step_count"] == 3
    assert metrics["reasoning_advantage/alignment_failure_count"] == 0

    entropys = torch.ones_like(batch.batch["responses"], dtype=torch.float32)
    entropys[0, [0, -1]] = float("nan")
    attach_reasoning_entropy(batch, tokenizer, entropys, None)
    assert batch.non_tensor_batch["entropy_alignment_status"].tolist() == ["aligned"]
    summaries = batch.non_tensor_batch["reasoning_step_entropies"][0]
    # UTF-8 characters split across tokens contribute every generated byte token.
    for number, text in enumerate(batch.non_tensor_batch["reasoning_trace"][0]["steps"], 1):
        assert summaries[f"step_{number}"] == {
            "mean": 1, "sum": len(text.encode("utf-8")), "token_count": len(text.encode("utf-8"))}
    assert batch.non_tensor_batch["answer_entropy"][0] == {"mean": 1, "sum": 4, "token_count": 4}


def test_offsets_cover_each_byte_of_unicode_and_skip_middle_special_token(byte_tokenizer):
    ids = byte_tokenizer.encode("a🙂éz", add_special_tokens=False)
    ids.insert(3, byte_tokenizer.pad_token_id)  # Inside the emoji's byte sequence.
    output = byte_tokenizer.decode(ids, skip_special_tokens=True, clean_up_tokenization_spaces=False)
    positions, offsets, status = response_token_offsets(byte_tokenizer, ids, output)
    assert status == "aligned"
    assert 3 not in positions
    assert offsets == [(0, 1), *[(1, 2)] * 4, *[(2, 3)] * 2, (3, 4)]


def test_changed_text_is_rejected(byte_tokenizer):
    ids = byte_tokenizer.encode("Found it .", add_special_tokens=False)
    positions, offsets, status = response_token_offsets(byte_tokenizer, ids, "Found it.")
    assert status == "token_id_mismatch"
    assert positions == offsets == []


def test_malformed_utf8_fails_conservatively(byte_tokenizer):
    ids = byte_tokenizer.encode("🙂", add_special_tokens=False)[:1]
    output = byte_tokenizer.decode(ids, clean_up_tokenization_spaces=False)
    positions, offsets, status = response_token_offsets(byte_tokenizer, ids, output)
    assert status == "token_id_mismatch"
    assert positions == offsets == []


def test_prompt_supplied_think_tag_and_stale_trace(byte_tokenizer):
    output = "Found it .\nChoose it.</think><action>look</action>"
    batch = make_token_batch(byte_tokenizer, byte_tokenizer.encode(output, add_special_tokens=False))
    batch.batch["prompts"] = torch.tensor([byte_tokenizer.encode("<think>", add_special_tokens=False)])
    attach_reasoning_steps(batch, byte_tokenizer, None)
    attach_reasoning_token_ids(batch, byte_tokenizer, None)
    assert batch.non_tensor_batch["reasoning_alignment_status"][0] == "aligned"
    batch.non_tensor_batch["reasoning_trace"][0]["steps"][0] = "Found it."
    with pytest.raises(ValueError, match="disagrees with submitted trace"):
        attach_reasoning_token_ids(batch, byte_tokenizer, None)
    with pytest.raises(ValueError, match="disagrees with saved trace"):
        attach_reasoning_entropy(batch, byte_tokenizer, torch.ones_like(batch.batch["responses"]), None)


def test_cached_search_tokenizer():
    """Run against the Search launcher's tokenizer when it is cached locally."""
    model = "Qwen/Qwen2.5-3B-Instruct"
    action = "Lima population"
    try:
        snapshot = snapshot_download(model, local_files_only=True)
    except LocalEntryNotFoundError:
        pytest.skip(f"Tokenizer for {model} is not cached locally")
    # A local path also avoids metadata probes in Transformers' tokenizer fixes.
    tokenizer = AutoTokenizer.from_pretrained(snapshot, local_files_only=True)
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token = tokenizer.eos_token
    output = f"<think>Found it .\nCheck café 🙂?\nChoose it.</think><search>{action}</search>"
    # Valid generated IDs need not use the encoder's preferred BPE segmentation.
    ids = [token for char in output for token in tokenizer.encode(char, add_special_tokens=False)]
    assert tokenizer.decode(ids, skip_special_tokens=True, clean_up_tokenization_spaces=False) == output
    assert tokenizer.encode(output, add_special_tokens=False) != ids
    batch = make_token_batch(tokenizer, ids)
    attach_reasoning_steps(batch, tokenizer, None)
    attach_reasoning_token_ids(batch, tokenizer, None)
    attach_reasoning_entropy(batch, tokenizer, torch.ones_like(batch.batch["responses"], dtype=torch.float32), None)
    assert batch.non_tensor_batch["reasoning_trace"][0]["steps"][0] == "Found it ."
    assert batch.non_tensor_batch["reasoning_alignment_status"].tolist() == ["aligned"]
    assert batch.non_tensor_batch["entropy_alignment_status"].tolist() == ["aligned"]
    assert batch.non_tensor_batch["answer_entropy"][0]["token_count"] > 0
    for number, expected in enumerate(batch.non_tensor_batch["reasoning_trace"][0]["steps"], 1):
        assigned = batch.batch["responses"][0, batch.batch["reasoning_step_ids"][0] == number]
        assert tokenizer.decode(assigned, clean_up_tokenization_spaces=False) == expected
